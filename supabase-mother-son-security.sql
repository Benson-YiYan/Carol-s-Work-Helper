create or replace function public.lcb_protect_matter_access_fields() returns trigger
language plpgsql security definer set search_path=public as $$
declare uid text:=public.lcb_app_user_id();
begin
  if uid is null then raise exception 'unknown app user'; end if;
  if uid<>'carol' and old.data->>'owner'<>new.data->>'owner' then
    raise exception 'only Carol can transfer ownership';
  end if;
  if uid<>'carol' and uid<>old.data->>'owner'
    and old.data->'deletedAt' is distinct from new.data->'deletedAt' then
    raise exception 'only the owner can move a matter to or from trash';
  end if;
  if uid<>'carol' and uid<>old.data->>'owner' and old.data->'team' is distinct from new.data->'team' then
    raise exception 'only the owner can change members';
  end if;
  return new;
end $$;
drop trigger if exists lcb_protect_matter_access_fields on public.matters;
create trigger lcb_protect_matter_access_fields before update on public.matters
for each row execute function public.lcb_protect_matter_access_fields();

