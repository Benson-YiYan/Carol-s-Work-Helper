create or replace function public.lcb_store_wrapped_keys(payload jsonb) returns void
language plpgsql security definer set search_path=public as $$
declare item jsonb; mid text; uid text:=public.lcb_app_user_id(); matter_data jsonb;
begin
  if uid is null then raise exception 'unknown app user'; end if;
  for item in select value from jsonb_array_elements(payload)
  loop
    mid:=item->>'matter_id';
    select data into matter_data from public.matters where data->>'id'=mid limit 1;
    if matter_data is null or not (uid='carol' or matter_data->>'owner'=uid) then
      raise exception 'not allowed to manage matter keys';
    end if;
    if item->>'user_id'<>'carol' and item->>'user_id'<>matter_data->>'owner'
      and not (coalesce(matter_data->'team','[]'::jsonb) ? (item->>'user_id')) then
      raise exception 'invalid key recipient';
    end if;
    insert into public.lcb_matter_keys(matter_id,user_id,wrapped_key)
    values(mid,item->>'user_id',item->>'wrapped_key')
    on conflict(matter_id,user_id) do update set wrapped_key=excluded.wrapped_key;
  end loop;
  for mid in select distinct value->>'matter_id' from jsonb_array_elements(payload)
  loop
    delete from public.lcb_matter_keys k where k.matter_id=mid and k.user_id<>'carol'
      and not exists(select 1 from jsonb_array_elements(payload) p where p->>'matter_id'=mid and p->>'user_id'=k.user_id);
  end loop;
end $$;
revoke all on function public.lcb_store_wrapped_keys(jsonb) from public,anon;
grant execute on function public.lcb_store_wrapped_keys(jsonb) to authenticated;

